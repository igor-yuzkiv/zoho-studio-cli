import type { z } from 'zod'

import type { ZohoFieldCreate } from '../../entities/field'

import type {
    fieldOptionSchemas,
    FieldDataType,
    picklistValueSchema,
    tooltipSchema,
} from './migration-definition.schemas'

/**
 * A text alone shows as an info icon next to the field; `static_text` shows inside the empty field,
 * which only fields typed into support.
 */
export type FieldTooltip = z.input<typeof tooltipSchema>
export type PicklistValue = z.input<typeof picklistValueSchema>

type OptionsOf<Type extends FieldDataType> = z.input<(typeof fieldOptionSchemas)[Type]>

export type FieldOptions = OptionsOf<'email'>
export type TextOptions = OptionsOf<'text'>
export type TextareaOptions = OptionsOf<'textarea'>
export type DoubleOptions = OptionsOf<'double'>
export type DecimalOptions = OptionsOf<'percent'>
export type CurrencyOptions = OptionsOf<'currency'>
export type PicklistOptions = OptionsOf<'picklist'>
export type LookupOptions = OptionsOf<'lookup'>

/** One `schema.<type>(label, options)` call, kept as written so it can be validated before use. */
export interface FieldDeclaration {
    label: string
    dataType: FieldDataType
    options: Record<string, unknown>
}

export interface FieldSchema {
    text(label: string, options?: TextOptions): void
    textarea(label: string, options?: TextareaOptions): void
    email(label: string, options?: FieldOptions): void
    phone(label: string, options?: TextOptions): void
    website(label: string, options?: FieldOptions): void
    integer(label: string, options?: TextOptions): void
    bigint(label: string, options?: TextOptions): void
    double(label: string, options?: DoubleOptions): void
    percent(label: string, options?: DecimalOptions): void
    currency(label: string, options?: CurrencyOptions): void
    date(label: string, options?: FieldOptions): void
    datetime(label: string, options?: FieldOptions): void
    boolean(label: string, options?: FieldOptions): void
    picklist(label: string, options: PicklistOptions): void
    multiselectpicklist(label: string, options: PicklistOptions): void
    lookup(label: string, options: LookupOptions): void
    userlookup(label: string, options?: FieldOptions): void
}

export type FieldsDeclaration = (schema: FieldSchema) => void

export interface CreateModuleMigration {
    /** Generated by Zoho from `plural_label` when left out. */
    api_name?: string
    singular_label: string
    plural_label: string
    /** Names of the profiles that get the module; only `Administrator` when left out. */
    profiles?: string[]
    fields: FieldsDeclaration
}

export interface UpdateModuleMigration {
    /** API name of the existing module the fields are added to. */
    module: string
    fields: FieldsDeclaration
}

export type MigrationDefinition =
    | { create: CreateModuleMigration; update?: never }
    | { update: UpdateModuleMigration; create?: never }

/** A migration reduced to data: what the run will send, with nothing left to execute. */
export type MigrationDescription =
    | {
          action: 'create'
          module: { api_name?: string; singular_label: string; plural_label: string }
          profiles: string[]
          fields: ZohoFieldCreate[]
      }
    | {
          action: 'update'
          module: { api_name: string }
          fields: ZohoFieldCreate[]
      }
